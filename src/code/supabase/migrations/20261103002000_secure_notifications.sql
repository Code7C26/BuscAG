begin;
-- Replace the complete client policy set: old permissive policies combine with OR.
-- Snapshot existing policies/ACLs before applying; see SECURITY_ROLLOUT.md.
do $$
declare r record; column_list text; target text;
begin
  for r in select tablename, policyname from pg_catalog.pg_policies
    where schemaname = 'public' and tablename in ('notifications')
  loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
  foreach target in array array['notifications']
  loop
    execute format('revoke all privileges on table public.%I from public, anon, authenticated', target);
    select string_agg(format('%I', a.attname), ', ' order by a.attnum)
      into column_list
      from pg_catalog.pg_attribute a
      where a.attrelid = format('public.%I', target)::regclass
        and a.attnum > 0 and not a.attisdropped;
    -- Table REVOKE does not remove old column-level grants.
    execute format('revoke all privileges (%s) on table public.%I from public, anon, authenticated', column_list, target);
    execute format('alter table public.%I enable row level security', target);
  end loop;
end;
$$;

grant select on public.notifications to authenticated;
grant insert (user_id, title, message, type, related_item_id)
  on public.notifications to authenticated;
grant update (is_read) on public.notifications to authenticated;
create policy notifications_read_self on public.notifications for select to authenticated
  using (user_id = (select auth.uid()));
-- The frontend creates only its own match notices. System/message/recovered
-- notices are generated by trusted database triggers, never by the client.
create policy notifications_insert_match on public.notifications for insert to authenticated
  with check (user_id = (select auth.uid()) and type = 'match');
create policy notifications_read_receipt on public.notifications for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
commit;
